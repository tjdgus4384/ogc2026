"""column_master.py -- bay-column recombination for OGC solutions.

The abstraction is deliberately small:

  * A column is one complete bay plan extracted from a feasible solution.
  * A recombined solution chooses exactly one column per bay.
  * Every block must be covered by exactly one chosen column.

Because bays are independent, recombining feasible bay columns is feasible as
long as the selected columns form an exact partition of the block set. The
master is a restricted set-partitioning model over columns generated by other
methods. This lets heterogeneous heuristics contribute partial wins without
turning the submission router into instance-specific gate logic.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
import time
from typing import Iterable


@dataclass(frozen=True)
class Column:
    bay: int
    blocks: tuple[int, ...]
    placements: tuple[tuple[int, int, int, int, int, int], ...]
    z1: int
    z3: int
    workload: int
    tag: str = ""


def _solution_obj(utils, prob: dict, sol: dict) -> float:
    try:
        r = utils.check_feasibility(prob, sol)
        return r["objective"] if r.get("feasible") else float("inf")
    except Exception:
        return float("inf")


def _parse_solution(prob: dict, sol: dict, utils) -> dict[int, tuple[int, int, int, int, int, int]] | None:
    """Return bid -> (bay, x, y, orient, entry, exit) for a feasible solution."""
    try:
        r = utils.check_feasibility(prob, sol)
    except Exception:
        return None
    if not r.get("feasible"):
        return None

    ent: dict[int, tuple[int, int, int, int, int]] = {}
    ext: dict[int, int] = {}
    for tt, ops in sol.get("operations", {}).items():
        t = int(tt)
        for op in ops:
            if op.get("type") == "ENTRY":
                ent[op["block_id"]] = (
                    int(op["bay_id"]),
                    int(round(float(op.get("x", 0)))),
                    int(round(float(op.get("y", 0)))),
                    int(op.get("orient_idx", 0)),
                    t,
                )
            elif op.get("type") == "EXIT":
                ext[op["block_id"]] = t

    n = len(prob.get("blocks", []))
    if len(ent) != n or len(ext) != n:
        return None
    out: dict[int, tuple[int, int, int, int, int, int]] = {}
    for bid in range(n):
        if bid not in ent or bid not in ext:
            return None
        bay, x, y, oi, e = ent[bid]
        out[bid] = (bay, x, y, oi, e, int(ext[bid]))
    return out


def extract_columns(prob: dict, sol: dict, utils, tag: str = "") -> list[Column]:
    """Extract one complete column per bay from a feasible full solution."""
    parsed = _parse_solution(prob, sol, utils)
    if parsed is None:
        return []
    nb = len(prob["bays"])
    by_bay: list[list[int]] = [[] for _ in range(nb)]
    for bid, rec in parsed.items():
        by_bay[rec[0]].append(bid)

    cols: list[Column] = []
    for j in range(nb):
        ids = tuple(sorted(by_bay[j]))
        placements = []
        z1 = z3 = workload = 0
        for bid in ids:
            bay, x, y, oi, e, f = parsed[bid]
            blk = prob["blocks"][bid]
            placements.append((bid, bay, x, y, oi, e, f))
            z1 += max(0, f - int(blk["due_date"]))
            z3 += max(blk["bay_preferences"]) - blk["bay_preferences"][j]
            workload += int(blk.get("workload", 0))
        cols.append(Column(
            bay=j,
            blocks=ids,
            placements=tuple(sorted(placements)),
            z1=int(z1),
            z3=int(z3),
            workload=int(workload),
            tag=tag,
        ))
    return cols


def _empty_columns(prob: dict) -> list[Column]:
    return [
        Column(bay=j, blocks=(), placements=(), z1=0, z3=0, workload=0, tag="empty")
        for j in range(len(prob["bays"]))
    ]


def _dedupe_columns(prob: dict, cols: Iterable[Column], max_per_bay: int = 80) -> list[Column]:
    """Keep the best column per (bay, block-set), then cap each bay by local cost."""
    w = prob.get("weights", {})
    w1, w3 = w.get("w1", 1), w.get("w3", 1)
    best: dict[tuple[int, tuple[int, ...]], Column] = {}
    for c in cols:
        key = (c.bay, c.blocks)
        old = best.get(key)
        if old is None or (w1 * c.z1 + w3 * c.z3, c.z1) < (w1 * old.z1 + w3 * old.z3, old.z1):
            best[key] = c

    by_bay: dict[int, list[Column]] = {}
    for c in best.values():
        by_bay.setdefault(c.bay, []).append(c)

    out: list[Column] = []
    for j in range(len(prob["bays"])):
        arr = by_bay.get(j, [])
        arr.sort(key=lambda c: (w1 * c.z1 + w3 * c.z3, c.z1, len(c.blocks)))
        out.extend(arr[:max_per_bay])
    return out


def _build_solution(cols: Iterable[Column]) -> dict:
    from solve import build_ops

    placements = {}
    for c in cols:
        for bid, bay, x, y, oi, e, f in c.placements:
            placements[bid] = (bay, x, y, oi, e, f)
    return build_ops(placements)


def recombine(prob: dict, sols: list[dict], utils, time_budget: float = 3.0,
              max_per_bay: int = 80, verbose: bool = False) -> dict:
    """Return the best of input solutions and a CP-SAT bay-column recombination."""
    t0 = time.time()
    feasible = [(s, _solution_obj(utils, prob, s)) for s in sols]
    feasible = [(s, o) for s, o in feasible if math.isfinite(o)]
    if not feasible:
        return sols[0] if sols else {"operations": {}}
    best_sol, best_obj = min(feasible, key=lambda x: x[1])

    cols: list[Column] = _empty_columns(prob)
    for idx, (s, _) in enumerate(feasible):
        cols.extend(extract_columns(prob, s, utils, tag=f"s{idx}"))
    cols = _dedupe_columns(prob, cols, max_per_bay=max_per_bay)

    n = len(prob["blocks"])
    nb = len(prob["bays"])
    if not cols or time.time() - t0 >= time_budget:
        return best_sol

    try:
        from ortools.sat.python import cp_model
    except Exception:
        return best_sol

    model = cp_model.CpModel()
    x = [model.NewBoolVar(f"c{k}") for k in range(len(cols))]

    for j in range(nb):
        model.Add(sum(x[k] for k, c in enumerate(cols) if c.bay == j) == 1)
    for bid in range(n):
        model.Add(sum(x[k] for k, c in enumerate(cols) if bid in c.blocks) == 1)

    z1 = sum(x[k] * cols[k].z1 for k in range(len(cols)))
    z3 = sum(x[k] * cols[k].z3 for k in range(len(cols)))

    loads = []
    total_work = sum(int(b.get("workload", 0)) for b in prob["blocks"])
    for j in range(nb):
        v = model.NewIntVar(0, total_work, f"load{j}")
        model.Add(v == sum(x[k] * cols[k].workload for k, c in enumerate(cols) if c.bay == j))
        loads.append(v)

    areas = [int(b["width"]) * int(b["height"]) for b in prob["bays"]]
    avg_area = sum(areas) / max(1, nb)
    scale = 1000
    u = [max(1, int(round(avg_area / a * scale))) for a in areas]
    weighted = []
    for j in range(nb):
        v = model.NewIntVar(0, max(u) * total_work, f"wload{j}")
        model.Add(v == loads[j] * u[j])
        weighted.append(v)
    spread = model.NewIntVar(0, max(u) * total_work, "spread")
    if nb >= 2:
        for a in range(nb):
            for b in range(nb):
                if a != b:
                    model.Add(spread >= weighted[a] - weighted[b])
    else:
        model.Add(spread == 0)

    w = prob.get("weights", {})
    w1, w2, w3 = int(w.get("w1", 1)), int(w.get("w2", 1)), int(w.get("w3", 1))
    model.Minimize(scale * (w1 * z1 + w3 * z3) + w2 * spread)

    solver = cp_model.CpSolver()
    solver.parameters.max_time_in_seconds = max(0.05, float(time_budget - (time.time() - t0)))
    solver.parameters.num_search_workers = 1
    status = solver.Solve(model)
    if status not in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        return best_sol

    chosen = [cols[k] for k in range(len(cols)) if solver.Value(x[k])]
    cand = _build_solution(chosen)
    r = utils.check_feasibility(prob, cand)
    if verbose:
        print(f"[column_master] cols={len(cols)} chosen={len(chosen)} "
              f"cand={r.get('objective') if r.get('feasible') else 'INF'} best={best_obj:.0f}")
    if r.get("feasible") and r["objective"] < best_obj - 1e-9:
        return cand
    return best_sol
